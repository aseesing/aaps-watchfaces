// The data model of the chart library hellocharts 1.5.8 (package lecho.lib.hellocharts.model), as far as
// the watch uses it: Line, PointValue, Axis, AxisValue, LineChartData, Viewport. The Kotlin code of the
// watch fills this model, and LineChartRenderer.ts draws it.
//
// Follows model/Line.java, PointValue.java, Axis.java, AxisValue.java, LineChartData.java,
// AbstractChartData.java, Viewport.java, ValueShape.java and util/ChartUtils.java of the library.
// The fields have the names and the defaults of the library. A setter of the library (`setColor(c)`,
// `setHasLines(b)`) is a plain field here (`color = c`, `hasLines = b`).
//
// Left out, the watch does not use it: labels at the points, the darker colour of a touched point,
// the name and the typeface of an axis, tilted labels, the formatters, animation.

import type { Argb } from "../../color.ts";

/** The colour of a line that got no colour (`ChartUtils.DEFAULT_COLOR`). */
export const DEFAULT_COLOR: Argb = 0xffdfdfdf;

/** The colour of the grid lines of an axis that got no colour (`ChartUtils.DEFAULT_DARKEN_COLOR`). */
export const DEFAULT_DARKEN_COLOR: Argb = 0xffdddddd;

/** `Color.LTGRAY` of Android: the colour of the labels of an axis that got no colour. */
export const LTGRAY: Argb = 0xffcccccc;

/** A point colour of 0 means: the colour of the line (`Line.UNINITIALIZED`). */
export const UNINITIALIZED: Argb = 0;

const DEFAULT_LINE_STROKE_WIDTH_DP = 3;
const DEFAULT_POINT_RADIUS_DP = 6;
const DEFAULT_AREA_TRANSPARENCY = 64;
const DEFAULT_TEXT_SIZE_SP = 12;
const DEFAULT_MAX_AXIS_LABEL_CHARS = 3;
const DEFAULT_BASE_VALUE = 0.0;

/** The shape of the points of a line. */
export type ValueShape = "CIRCLE" | "SQUARE" | "DIAMOND";

/**
 * Android's `DashPathEffect`: a line drawn in dashes. [intervals] are the lengths of dash, gap, dash, gap
 * and so on, in pixels of the watch (not dp). [phase] is how far into that row the line starts.
 */
export interface DashPathEffect {
    intervals: number[];
    phase: number;
}

/**
 * One point of a line. The library keeps x and y as 32 bit floats, so they are rounded to that here too.
 * This shows: a time in whole minutes since 1970 is a big number, and as a float it is only right to
 * 2 minutes. The points of the watch are at those rounded places.
 */
export class PointValue {
    x: number;
    y: number;

    constructor(x: number, y: number) {
        this.x = Math.fround(x);
        this.y = Math.fround(y);
    }
}

/** One line of the chart: a row of points, drawn as a line, as loose points, or both. */
export class Line {
    color: Argb = DEFAULT_COLOR;
    /** The colour of the points. [UNINITIALIZED]: the colour of the line. */
    pointColor: Argb = UNINITIALIZED;
    /** The alpha (0..255) of the filled area under the line, when [isFilled]. */
    areaTransparency: number = DEFAULT_AREA_TRANSPARENCY;
    /** In dp. */
    strokeWidth: number = DEFAULT_LINE_STROKE_WIDTH_DP;
    /** In dp. */
    pointRadius: number = DEFAULT_POINT_RADIUS_DP;
    hasPoints = true;
    hasLines = true;
    /** A smooth curve through the points. */
    isCubic = false;
    /** Steps: first to the side, then up or down. */
    isSquare = false;
    isFilled = false;
    shape: ValueShape = "CIRCLE";
    pathEffect: DashPathEffect | null = null;
    values: PointValue[];

    constructor(values: PointValue[] = []) {
        this.values = values;
    }
}

/** One place on an axis, with the text shown there. Without a [label] the number itself is shown. */
export class AxisValue {
    value: number;
    label: string | null = null;

    constructor(value: number) {
        this.value = Math.fround(value);
    }

    setLabel(label: string): this {
        this.label = label;
        return this;
    }
}

/** One axis: the labels on one side of the chart, and the grid lines that belong to them. */
export class Axis {
    /** In sp. */
    textSize: number = DEFAULT_TEXT_SIZE_SP;
    /** The room kept for a label, as a number of characters. The library allows 0 to 32. */
    maxLabelChars: number = DEFAULT_MAX_AXIS_LABEL_CHARS;
    /** True: the library chooses the values itself. Setting [values] turns this off, see there. */
    isAutoGenerated = true;
    /** Grid lines, one at each value. */
    hasLines = false;
    /** The labels are drawn inside the plot, and take no room beside it. */
    isInside = false;
    textColor: Argb = LTGRAY;
    lineColor: Argb = DEFAULT_DARKEN_COLOR;
    /** A line between the labels and the plot, in [textColor]. */
    hasSeparationLine = true;
    private axisValues: AxisValue[] = [];

    /** With [values] the axis is not auto generated, like `Axis(values)` of the library. */
    constructor(values?: AxisValue[]) {
        if (values !== undefined) this.values = values;
    }

    get values(): AxisValue[] {
        return this.axisValues;
    }

    /**
     * Like `setValues` of the library: it also turns [isAutoGenerated] off. The watch code sets
     * `isAutoGenerated = true` first and the values after that, so its axis ends up not auto generated.
     */
    set values(values: AxisValue[]) {
        this.axisValues = values;
        this.isAutoGenerated = false;
    }
}

/** Everything of one chart: the lines and the four axes. */
export class LineChartData {
    lines: Line[];
    axisXBottom: Axis | null = null;
    axisYLeft: Axis | null = null;
    axisXTop: Axis | null = null;
    axisYRight: Axis | null = null;
    /** The value where a filled area ends. */
    baseValue: number = DEFAULT_BASE_VALUE;

    constructor(lines: Line[] = []) {
        this.lines = lines;
    }
}

/**
 * The data a chart view of the library shows until it gets other data: one grey line with 4 points
 * (`LineChartData.generateDummyData`). The watch shows it while it has no glucose for the graph.
 */
export function generateDummyData(): LineChartData {
    return new LineChartData([new Line([new PointValue(0, 2), new PointValue(1, 4), new PointValue(2, 3), new PointValue(3, 4)])]);
}

/** The values the chart shows: x from [left] to [right], y from [bottom] to [top]. */
export interface Viewport {
    left: number;
    top: number;
    right: number;
    bottom: number;
}
